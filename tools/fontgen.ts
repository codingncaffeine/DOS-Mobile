// ---------------------------------------------------------------- box drawing (generated)
// Single lines: vertical = columns 3-4, horizontal = rows 7-8.
// Double lines: vertical = columns 2-3 (L) and 5-6 (R); horizontal = rows 6-7 (T) and 9-10 (B).
// Each arm's lines run from the cell edge to a stop that depends on the perpendicular arms,
// which yields the classic open inner corners and broken crossings.
type Arm = 0 | 1 | 2;
function box(code: number, a: { up?: Arm; down?: Arm; left?: Arm; right?: Arm }) {
  const g: number[][] = Array.from({ length: 16 }, () => Array(8).fill(0));
  const up = a.up ?? 0, down = a.down ?? 0, left = a.left ?? 0, right = a.right ?? 0;
  const vspan = (cols: number[], r0: number, r1: number) => { for (let r = r0; r <= r1; r++) for (const c of cols) g[r][c] = 1; };
  const hspan = (rows: number[], c0: number, c1: number) => { for (const r of rows) for (let c = c0; c <= c1; c++) g[r][c] = 1; };
  const L = [2, 3], R = [5, 6], T = [6, 7], B = [9, 10], SV = [3, 4], SH = [7, 8];
  const anyHDouble = left === 2 || right === 2, anyVDouble = up === 2 || down === 2;
  // vertical arms
  if (up === 1) vspan(SV, 0, anyHDouble ? 10 : 8);
  if (down === 1) vspan(SV, anyHDouble ? 6 : 7, 15);
  if (up === 2) {
    vspan(L, 0, left ? 7 : right ? 10 : 8);
    vspan(R, 0, right ? 7 : left ? 10 : 8);
  }
  if (down === 2) {
    vspan(L, left ? 9 : right ? 6 : 7, 15);
    vspan(R, right ? 9 : left ? 6 : 7, 15);
  }
  // horizontal arms
  if (left === 1) hspan(SH, 0, anyVDouble ? 6 : 4);
  if (right === 1) hspan(SH, anyVDouble ? 2 : 3, 7);
  if (left === 2) {
    hspan(T, 0, up ? 3 : down ? 6 : 4);
    hspan(B, 0, down ? 3 : up ? 6 : 4);
  }
  if (right === 2) {
    hspan(T, up ? 5 : down ? 2 : 3, 7);
    hspan(B, down ? 5 : up ? 2 : 3, 7);
  }
  // single arms meeting double arms of the other axis: close the gap to the near line
  if (up === 1 && (left === 2 || right === 2)) vspan(SV, 0, 10);
  if (down === 1 && (left === 2 || right === 2)) vspan(SV, 6, 15);
  G.set(code, g.map((r) => r.map((v) => (v ? "#" : ".")).join("")));
}
